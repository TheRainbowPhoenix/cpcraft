uint8_t isin(uint16_t phase16)
{
    /* Top 8 bits = integer index, bottom 8 bits = fractional weight. */
    const uint8_t i0 = (uint8_t)((phase16 >> 8) & 0xFF);
    const uint8_t i1 = (uint8_t)(i0 + 1);
    const uint16_t frac = (uint16_t)(phase16 & 0xFF); /* 0..255 */
    const int32_t a = (int32_t)sin_lut8[i0];
    const int32_t b = (int32_t)sin_lut8[i1];

    return (uint8_t)(a + (((b - a) * (int32_t)frac) / 256));
}

